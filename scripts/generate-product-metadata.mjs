import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const registryPath = path.join(ROOT, "config", "product-identity.json");
const schemaPath = path.join(ROOT, "config", "product-identity.schema.json");
const checkOnly = process.argv.includes("--check");

export function validateProductIdentity(value) {
  const errors = [];
  const schema = JSON.parse(fs.readFileSync(schemaPath, "utf8"));

  function validateSchema(subject, shape, location = "identity") {
    if ("const" in shape && subject !== shape.const) errors.push(`${location} must equal ${JSON.stringify(shape.const)}`);
    if (shape.type === "object") {
      if (!subject || typeof subject !== "object" || Array.isArray(subject)) {
        errors.push(`${location} must be an object`);
        return;
      }
      for (const key of shape.required ?? []) if (!(key in subject)) errors.push(`${location} is missing '${key}'`);
      if (shape.additionalProperties === false) {
        const allowed = new Set(Object.keys(shape.properties ?? {}));
        for (const key of Object.keys(subject)) if (!allowed.has(key)) errors.push(`${location} has unexpected '${key}'`);
      }
      for (const [key, childShape] of Object.entries(shape.properties ?? {})) {
        if (key in subject) validateSchema(subject[key], childShape, `${location}.${key}`);
      }
    } else if (shape.type === "string") {
      if (typeof subject !== "string") errors.push(`${location} must be a string`);
      else if (shape.minLength && subject.length < shape.minLength) errors.push(`${location} must not be empty`);
    }
  }

  validateSchema(value, schema);
  if (value.schemaVersion !== 1) errors.push("schemaVersion must be 1");
  if (value.product?.name !== "Bayanly AI") errors.push("product.name must be 'Bayanly AI'");
  if (value.product?.shortName !== "Bayanly") errors.push("product.shortName must be 'Bayanly'");
  if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(value.product?.supportEmail ?? "")) errors.push("supportEmail is invalid");
  if (value.publisher?.legalStatus !== "REQUIRES_LEGAL_REVIEW") errors.push("publisher legal status must remain explicit");
  if (value.web?.isPlaceholder !== true || value.web?.operationalStatus !== "REQUIRES_DOMAIN_CONFIGURATION") errors.push("placeholder domain must be marked non-operational");
  if (value.desktop?.activeAppId !== "com.presenton.presenton" || value.desktop?.appIdStatus !== "COMPATIBILITY_RETAINED") errors.push("active desktop app ID must retain upgrade compatibility");
  for (const [name, color] of Object.entries(value.colors ?? {})) if (!/^#[0-9A-F]{6}$/.test(color)) errors.push(`color '${name}' must be uppercase #RRGGBB`);
  if (errors.length) throw new Error(`Invalid product identity:\n- ${errors.join("\n- ")}`);
  return value;
}

function generatedSource(identity) {
  return `// Generated by scripts/generate-product-metadata.mjs. Do not edit.\n` +
    `export const PRODUCT_IDENTITY = ${JSON.stringify(identity, null, 2)} as const;\n\n` +
    `export type ProductIdentity = typeof PRODUCT_IDENTITY;\n`;
}

function hexToHsl(hex) {
  const channels = [1, 3, 5].map((offset) => Number.parseInt(hex.slice(offset, offset + 2), 16) / 255);
  const [r, g, b] = channels;
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const lightness = (max + min) / 2;
  const delta = max - min;
  let hue = 0;
  if (delta) {
    if (max === r) hue = ((g - b) / delta) % 6;
    else if (max === g) hue = (b - r) / delta + 2;
    else hue = (r - g) / delta + 4;
    hue = Math.round(hue * 60);
    if (hue < 0) hue += 360;
  }
  const saturation = delta ? delta / (1 - Math.abs(2 * lightness - 1)) : 0;
  return `${hue} ${(saturation * 100).toFixed(1)}% ${(lightness * 100).toFixed(1)}%`;
}

function generatedCss(identity) {
  const variables = Object.entries(identity.colors).flatMap(([name, value]) => [
    `  --brand-${name}: ${value};`,
    `  --brand-${name}-hsl: ${hexToHsl(value)};`,
  ]).join("\n");
  return `/* Generated by scripts/generate-product-metadata.mjs. Do not edit. */\n:root {\n${variables}\n}\n`;
}

function main() {
  const identity = validateProductIdentity(JSON.parse(fs.readFileSync(registryPath, "utf8")));
  const source = generatedSource(identity);
  const targets = [
    { path: path.join(ROOT, "servers", "nextjs", "lib", "product-identity.ts"), source },
    { path: path.join(ROOT, "electron", "app", "generated", "product-identity.ts"), source },
    { path: path.join(ROOT, "servers", "nextjs", "app", "generated-brand.css"), source: generatedCss(identity) },
  ];
  let stale = false;
  for (const target of targets) {
    if (checkOnly) {
      if (!fs.existsSync(target.path) || fs.readFileSync(target.path, "utf8") !== target.source) {
        console.error(`Generated product metadata is stale: ${path.relative(ROOT, target.path)}`);
        stale = true;
      }
    } else {
      fs.mkdirSync(path.dirname(target.path), { recursive: true });
      fs.writeFileSync(target.path, target.source);
      console.log(`Generated ${path.relative(ROOT, target.path)}`);
    }
  }
  if (stale) process.exit(1);
  if (checkOnly) console.log("Generated product metadata is current.");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
